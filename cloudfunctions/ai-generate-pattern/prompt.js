function buildPrompt(opts) {
  const size = opts.size
  const style = opts.style || '卡通'
  const extraReq = String(opts.extra || '').trim() // 用户附加要求（如删掉画面中的某些元素），不覆盖风格
  const styleKey =
    opts.styleKey === 'custom'
      ? 'custom'
      : opts.styleKey === 'macaron'
        ? 'macaron'
        : opts.styleKey === 'realistic'
          ? 'realistic'
          : 'cartoon'
  const cutout = !!opts.cutout
  const subject = SUBJECT_SECTIONS[opts.subject] ? opts.subject : 'auto'
  const sections =
    styleKey === 'realistic'
      ? Object.assign({}, SUBJECT_SECTIONS, REAL_SUBJECT_SECTIONS)
      : SUBJECT_SECTIONS
  const parts = [
    '请把「第一张图」（用户照片）转换成 ' +
      size +
      '×' +
      size +
      ' 的拼豆像素图图纸：每个格子一个纯色块，格子紧密拼接、无缝隙，输出必须是单张完整的像素画，整体为 1:1 正方形。',
    '「色块均匀」输出图必须由 ' +
      size +
      '×' +
      size +
      ' 个纯色方块整齐排列，每个方块对应一格拼豆、占据约 (输出边长÷' +
      size +
      ')×(输出边长÷' +
      size +
      ') 像素的区域：方块内部所有像素只能是一种颜色，完全均匀，禁止渐变、混色、抗锯齿、杂点或深浅不一的像素；相邻方块交界处也不得有过渡混色，颜色要分明。',
    '「轮廓闭合」最重要的结构要求：所有轮廓线必须首尾相接、完全闭合，不能有缺口、断线或开口；主体与背景之间必须由连续的深色或非白色像素链完全隔开。主体内部的任何白色或浅色区域（如眼白、高光、白色衣物）必须被其他颜色完全包围，禁止与画面边缘的白色背景连通——否则内部白色会被误判为背景。',
    styleKey === 'realistic' ? FACE_REF_REAL[subject] : FACE_REF[subject],
    '⚠ 重点：这些示例只用于学习画法与转换思路，禁止照搬、复制或生成示例中的任何角色、动物、造型、服装、背景或具体内容，构图与内容必须完全来自「第一张图」（用户照片）。',
    '「重要」不要模仿参考图中的文字、水印、贴纸、标语或广告元素，输出画面中不得出现任何文字、数字或水印。',
    styleKey === 'realistic'
      ? '「拼豆友好」为了拼豆省力，细节归纳成整齐色块、细碎杂点合并，但保留原图的光影与质感层次：明暗渐变用 3~5 档色阶逐级过渡，不要压成平涂色块；关键细节（眼睛、五官、花纹、标志性部件）用 1~2 格色块精确表现，不能糊成一团或丢失特征。'
      : '「拼豆友好」为了拼豆省力，相邻区域尽量使用大块相同颜色：相近色合并成同一色块，渐变压缩成 2~3 档色阶，细碎纹理和杂点简化成整齐色块，避免拼豆时频繁换色；但必须保留识别主体的关键细节——整体轮廓、眼睛或五官、特征花纹/标志性部件与主要配色，关键细节用 1~2 格的色块精确表现，不能糊成一团或丢失特征。'
  ]
  if (subject === 'auto') {
    parts.push('「主体判断」先看「第一张图」判断主体类型：人物、动物、物体、虚拟形象或风景场景。本项目擅长人物：主体明确是人物时，严格按下方人物规则绘制；若明确不是人物（如动物、物体、风景场景、虚拟形象），按对应类别规则绘制，不要强行套用人物规则；无法确定时选择最接近的类别。')
    for (const key of ['person', 'animal', 'object', 'virtual', 'scenery']) {
      parts.push(...sections[key])
    }
  } else {
    parts.push(...sections[subject])
  }
  parts.push(
    '「描边」' + OUTLINE[styleKey],
    styleKey === 'realistic'
      ? '「颜色」整体控制在 20~40 种颜色内，按原图层次保留明暗与质感，配色与原图一致。'
      : '「颜色」整体控制在 12~20 种颜色内，配色与原图主色一致。',
    '「风格」' + style,
    extraReq ? '「额外要求」' + extraReq : '',
    cutout
      ? '「抠图」最重要的要求：背景只允许使用纯白色——每一个背景像素必须严格等于 RGB(255,255,255)（#FFFFFF），不允许任何近白色、米白、奶白、浅灰、灰白、阴影、渐变、晕影或轻微杂色；主体边缘与背景交界必须干净利落、无混色过渡、无残留背景色。主体以外不得出现任何原背景物体、家具、墙面、植物、阴影、渐变或装饰，如同把主体从照片中完整抠出后放在纯白画布上。'
      : '「背景」背景必须是纯白色（RGB 255,255,255），不要任何背景颜色、渐变或装饰。',
    '「禁止」不要画网格线、辅助线、边框；不要渐变或抗锯齿混色；不要文字、数字、水印、贴纸；不要多格拼接或九宫格。'
  )
  return parts.filter((s) => s).join('\n')
}

module.exports = { buildPrompt }
